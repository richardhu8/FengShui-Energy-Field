def delta_t(jd):
    """ΔT = TT − UT，秒。Espenak–Meeus 多项式（NASA 日食站所用）。

    VSOP87 的时间参数是力学时 TT，而节气要报的是世界时 UT。
    漏掉这一项会让结果系统性晚约 1 分钟 —— 实测正是如此。
    """
    y = 2000 + (jd - 2451545.0)/365.25
    if 2005 <= y < 2050:
        t = y - 2000
        return 62.92 + 0.32217*t + 0.005589*t*t
    if 1986 <= y < 2005:
        t = y - 2000
        return (63.86 + 0.3345*t - 0.060374*t**2 + 0.0017275*t**3
                + 0.000651814*t**4 + 0.00002373599*t**5)
    if 1961 <= y < 1986:
        t = y - 1975
        return 45.45 + 1.067*t - t*t/260 - t**3/718
    if 1941 <= y < 1961:
        t = y - 1950
        return 29.07 + 0.407*t - t*t/233 + t**3/2547
    if 1920 <= y < 1941:
        t = y - 1920
        return 21.20 + 0.84493*t - 0.076100*t*t + 0.0020936*t**3
    if 2050 <= y < 2150:
        return -20 + 32*((y-1820)/100)**2 - 0.5628*(2150-y)
    u = (y - 1820)/100
    return -20 + 32*u*u


def _series(terms, tau):
    return sum(a * math.cos(b + c * tau) for a, b, c in terms)

def sun_longitude_hp(jd):
    """太阳视黄经（度），jd 为世界时 UT。精度优于 0.001°。

    内部把 UT 转 TT 后再代入 VSOP87 —— 这一步不能省。
    """
    jd = jd + delta_t(jd)/86400.0
    tau = (jd - 2451545.0) / 365250.0
    T = tau * 10
    L = (_series(L0,tau) + _series(L1,tau)*tau + _series(L2,tau)*tau**2
         + _series(L3,tau)*tau**3 + _series(L4,tau)*tau**4 + _series(L5,tau)*tau**5) / 1e8
    theta = math.degrees(L) + 180.0                    # 日心 → 地心
    # FK5 修正
    lam_p = theta - 1.397*T - 0.00031*T*T
    theta += (-0.09033 + 0.03916*(math.cos(math.radians(lam_p))
                                  - math.sin(math.radians(lam_p)))*0) / 3600.0
    # 章动（主项即可：Δψ 的次要项 <0.5"，远小于本文件的定界需求）
    omega = 125.04452 - 1934.136261*T
    dpsi = (-17.20*math.sin(math.radians(omega))
            - 1.32*math.sin(math.radians(2*(280.4665+36000.7698*T)))
            - 0.23*math.sin(math.radians(2*(218.3165+481267.8813*T)))
            + 0.21*math.sin(math.radians(2*omega))) / 3600.0
    # 光行差 −20.4898″/R
    e = 0.016708634 - 0.000042037*T - 0.0000001267*T*T
    M = 357.52911 + 35999.05029*T - 0.0001537*T*T
    Mr = math.radians(M)
    C = ((1.914602 - 0.004817*T - 0.000014*T*T)*math.sin(Mr)
         + (0.019993 - 0.000101*T)*math.sin(2*Mr) + 0.000289*math.sin(3*Mr))
    v = M + C
    R = 1.000001018*(1 - e*e)/(1 + e*math.cos(math.radians(v)))
    aberr = -20.4898/R/3600.0
    return (theta + dpsi + aberr) % 360


def sun_longitude_lp(jd):
    """页面在用的 Meeus 低精度式（与 玄空飞星排盘.html 的 sunLon 同式）。"""
    T = (jd - 2451545.0)/36525.0
    L0_ = 280.46646 + 36000.76983*T + 0.0003032*T*T
    M = 357.52911 + 35999.05029*T - 0.0001537*T*T
    Mr = math.radians(M)
    C = ((1.914602 - 0.004817*T - 0.000014*T*T)*math.sin(Mr)
         + (0.019993 - 0.000101*T)*math.sin(2*Mr) + 0.000289*math.sin(3*Mr))
    omega = 125.04 - 1934.136*T
    return (L0_ + C - 0.00569 - 0.00478*math.sin(math.radians(omega))) % 360


def term_jd(year, lon, fn):
    """用给定的黄经函数求某年某节气的 UTC 儒略日。"""
    jd = jd_from_utc(year, 1, 1) + ((lon - 280) % 360)*365.2422/360
    for _ in range(60):
        d = ((fn(jd) - lon + 180) % 360) - 180
        jd -= d*365.2422/360
    return jd

def jd_from_utc(y, m, d, h=0.0):
    if m <= 2: y, m = y-1, m+12
    a = y//100; b = 2 - a + a//4
    return int(365.25*(y+4716)) + int(30.6001*(m+1)) + d + b - 1524.5 + h/24.0

def utc_from_jd(jd):
    z = math.floor(jd + 0.5); f = jd + 0.5 - z
    a = z
    if z >= 2299161:
        al = int((z - 1867216.25)/36524.25); a = z + 1 + al - al//4
    b = a + 1524; c = int((b - 122.1)/365.25); d = int(365.25*c); e = int((b-d)/30.6001)
    day = b - d - int(30.6001*e) + f
    mo = e - 1 if e < 14 else e - 13
    yr = c - 4716 if mo > 2 else c - 4715
    di = int(day)
    return yr, mo, di, (day - di)*24

